#!/bin/sh
# Regenerates src/sys.rs from the libghostty-vt headers in
# build/ghostty-vt.xcframework (pinned by scripts/ghostty-vt.sh).
# Needs `cargo install bindgen-cli` and Xcode's libclang.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
headers="$root/build/ghostty-vt.xcframework/macos-arm64_x86_64/Headers"
commit=$(cat "$root/build/ghostty-vt.xcframework/.commit")

export DEVELOPER_DIR=${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}
export LIBCLANG_PATH=${LIBCLANG_PATH:-$DEVELOPER_DIR/Toolchains/XcodeDefault.xctoolchain/usr/lib}

out="$here/src/sys.rs"
{
  echo "// Generated by core/vt/regen-sys.sh from libghostty-vt $commit. Do not edit."
  bindgen "$headers/ghostty/vt.h" \
    --allowlist-function 'ghostty_.*' \
    --allowlist-type 'Ghostty.*' \
    --allowlist-var 'GHOSTTY_.*' \
    --default-enum-style consts \
    --no-prepend-enum-name \
    --no-doc-comments \
    --no-layout-tests \
    --raw-line '#![allow(non_upper_case_globals, non_camel_case_types, non_snake_case, dead_code, clippy::all)]' \
    -- -I"$headers" -DGHOSTTY_STATIC -target arm64-apple-macos
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
